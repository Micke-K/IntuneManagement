# Markdown output provider.
#
# Consumes the per-object documentation result (see DocumentationOutputJson.ps1
# header for the field list). Renders HTML-tabled markdown with CSS styling
# from Internal/Documentation/Assets/DefaultMDStyle.css (or a user-supplied .css file).
#
# Differences vs old DocumentationMD.psm1:
#   - Drops V1 NewObjectGroup/NewObjectType hooks; V2 (string-arg) is registered
#   - Drops the extended/custom property selectors that read $global:cb*/$global:txt*
#     UI controls. Always uses DefaultDocumentationProperties or ('Name','Value').
#     Phase 2 [DocumentationContext] will reintroduce these via $ctx.Options.
#   - Drops the unused commented-out block at end of Invoke-MDPostProcessItems
#   - Uses the typed-object API: $PolicyObject.Name + $PolicyObject.PolicyType.Title
#     instead of Get-GraphObjectName $obj $objectType + $objectType.Title

function Invoke-InitializeMDOutput {
    Add-DocumentationOutputProvider ([PSCustomObject]@{
        Name              = "Markdown"
        Value             = "md"
        # Path metadata (see DocumentationOutputHTML.ps1 header comment).
        # UI browse-button wiring lives in
        # UI/<backend>/ClassExtensions/DocumentationOutputMDUIExtension.ps1.
        PrimaryPathOption = "MDDocumentName"
        PathIsFolder      = $false
        PreProcess        = { Invoke-MDPreProcessItems @args }
        NewObjectGroup    = { Invoke-MDNewObjectGroup @args }
        NewObjectType     = { Invoke-MDNewObjectType @args }
        Process           = { Invoke-MDProcessItem @args }
        PostProcess       = { Invoke-MDPostProcessItems @args }
        ProcessAllObjects = { Invoke-MDProcessAllObjects @args }
    })
}

