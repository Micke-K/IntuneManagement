function Invoke-MDPreProcessItems {
    $script:sectionAnchors      = @()
    $script:totAnchors          = @()
    $script:mdStrings           = $null
    $script:currentItemFileName = $null

    $defaultCSSFile = [IO.Path]::Combine($script:AppRootFolder, "Internal", "Documentation", "Assets", "DefaultMDStyle.css")
    $mdCssFile = Get-DocumentationOutputOption md "MDCSSFile" $defaultCSSFile
    $includeCss = (Get-DocumentationOutputOption md "MDIncludeCSS" $true) -eq $true

    if (-not $mdCssFile) {
        Write-Log "CSS file not specified. Using default" 2
        $mdCssFile = $defaultCSSFile
    }
    elseif (-not [IO.File]::Exists($mdCssFile)) {
        Write-Log "CSS file $mdCssFile not found. Using default" 2
        $mdCssFile = $defaultCSSFile
    }

    if ($includeCss -and [IO.File]::Exists($mdCssFile)) {
        Write-Log "Using CSS file $mdCssFile"
        $script:cssStyle = ([IO.File]::ReadAllText($mdCssFile)) + [Environment]::NewLine
    }
    else {
        Write-Log "CSS file $mdCssFile not found. No styles applied" 2
        $script:cssStyle = ""
    }

    $fileName = Get-DocumentationOutputOption md "MDDocumentName" ""
    if (-not $fileName) { $fileName = "%MyDocuments%\%Organization%-%Date%.md" }
    $fileName = Expand-FileName $fileName

    $script:outFile      = $fileName
    $script:documentPath = [IO.Path]::GetDirectoryName($fileName)
    $script:outputType   = Get-DocumentationOutputOption md "MDDocumentFileType" "Full"

    if ($script:outputType -eq "Object") {
        Write-Log "Document one file for each object + index file"
    }
    else {
        Write-Log "Document one single file for all objects"
        $script:outputType = "Full"
        $script:mdStrings  = [System.Text.StringBuilder]::new()
    }
}

function Invoke-MDPostProcessItems {
    $userName = $null
    $mail     = ""
    $me = Get-CurrentUser
    if ($me) {
        if ($me.givenName -and $me.surname) {
            $userName = "$($me.givenName) $($me.surname)"
        }
        else {
            $userName = $me.displayName
        }
        if ($me.mail) { $mail = " ($($me.mail))" }
    }

    $orgName = Get-CurrentOrganizationName

    $title = Get-DocumentationOutputOption md "MDTitleProperty" "Intune documentation"
    if (-not $title) { $title = "Intune documentation" }

    $mdContent = [System.Text.StringBuilder]::new()
    [void]$mdContent.AppendLine("# $title")
    [void]$mdContent.AppendLine("")
    [void]$mdContent.AppendLine("")

    if (-not ((Get-DocumentationOption "SkipDocumentInfo" $false) -eq $true)) {
        if ($orgName)  { [void]$mdContent.AppendLine("*Organization:* $orgName`n") }
        if ($userName) { [void]$mdContent.AppendLine("*Generated by:* $userName$mail`n") }

        $skipDate = (Get-DocumentationOutputOption md "MDDocumentSkipDate" $false) -eq $true
        if (-not $skipDate) {
            [void]$mdContent.AppendLine("*Generated:* $((Get-Date).ToShortDateString()) $((Get-Date).ToLongTimeString())`n")
        }
    }

    if ($script:sectionAnchors.Count -gt 0) {
        [void]$mdContent.AppendLine("")
        [void]$mdContent.AppendLine("## Table of Contents")
    }

    foreach ($header in $script:sectionAnchors) {
        $indent = [string]::new(" ", (($header.Level - 1) * 2))
        [void]$mdContent.AppendLine("$indent- [$($header.Name)]($($header.FileName)#$($header.Anchor))`n")
    }
    [void]$mdContent.AppendLine("")

    $mdText = $script:cssStyle + $mdContent.ToString()
    if ($script:outputType -eq "Full" -and $script:mdStrings) {
        $mdText += $script:mdStrings.ToString()
    }

    Save-DocumentationFile $mdText $script:outFile -OpenFile:((Get-DocumentationOutputOption md "MDOpenFile" $true) -eq $true)
}

