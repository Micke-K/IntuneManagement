# HTML output provider.
#
# Consumes the per-object documentation result (see DocumentationOutputJson.ps1
# header for the field list). Renders a single HTML document (or one file per
# object) with CSS from Internal/Documentation/Assets/DefaultHTMLStyle.css.
#
# Differences vs old DocumentationHTML.psm1:
#   - Drops V1 NewObjectGroup/NewObjectType hooks (V2 string-arg is registered)
#   - Drops extended/custom property selectors that read $global:txt*/$global:cb*
#     UI controls. Always uses DefaultDocumentationProperties or ('Name','Value').
#     Phase 2 [DocumentationContext] will reintroduce these via $ctx.Options.
#   - Uses the typed-object API: $PolicyObject.Name + $PolicyObject.PolicyType.Title
#   - Invoke-HTMLProcessAllObjects (ScopeTags consolidated table) is stubbed
#     because Get-TableObjects doesn't exist yet — wire up in phase 2.

function Invoke-InitializeHTMLOutput {
    Add-DocumentationOutputProvider ([PSCustomObject]@{
        Name              = "HTML"
        Value             = "html"
        # Path metadata for the bulk-doc UI: which option key stores the
        # primary output path, and whether that path is a folder or a file.
        # File-picker button wiring for the UI is declared separately in
        # UI/<backend>/ClassExtensions/DocumentationOutputHTMLUIExtension.ps1
        # to keep XAML control names + toolkit-specific filter strings out
        # of this pure-logic file.
        PrimaryPathOption = "HTMLDocumentName"
        PathIsFolder      = $false
        PreProcess        = { Invoke-HTMLPreProcessItems @args }
        NewObjectGroup    = { Invoke-HTMLNewObjectGroup @args }
        NewObjectType     = { Invoke-HTMLNewObjectType @args }
        Process           = { Invoke-HTMLProcessItem @args }
        PostProcess       = { Invoke-HTMLPostProcessItems @args }
        ProcessAllObjects = { Invoke-HTMLProcessAllObjects @args }
    })
}

function Invoke-HTMLPreProcessItems {
    $script:sectionAnchors       = @()
    $script:totAnchors           = @()
    $script:htmlStrings          = $null
    $script:currentItemFileName  = $null

    $defaultCSSFile = [IO.Path]::Combine($script:AppRootFolder, "Internal", "Documentation", "Assets", "DefaultHTMLStyle.css")
    $htmlCssFile = Get-DocumentationOutputOption html "HTMLCSSFile" $defaultCSSFile

    if (-not $htmlCssFile) {
        Write-Log "CSS file not specified. Using default" 2
        $htmlCssFile = $defaultCSSFile
    }
    elseif (-not [IO.File]::Exists($htmlCssFile)) {
        Write-Log "CSS file $htmlCssFile not found. Using default" 2
        $htmlCssFile = $defaultCSSFile
    }

    if ([IO.File]::Exists($htmlCssFile)) {
        Write-Log "Using CSS file $htmlCssFile"
        $script:cssStyle = ([IO.File]::ReadAllText($htmlCssFile)) + [Environment]::NewLine
    }
    else {
        Write-Log "CSS file $htmlCssFile not found. No styles applied" 2
        $script:cssStyle = ""
    }

    $fileName = Get-DocumentationOutputOption html "HTMLDocumentName" ""
    if (-not $fileName) { $fileName = "%MyDocuments%\%Organization%-%Date%.html" }
    $fileName = Expand-FileName $fileName

    $script:outFile      = $fileName
    $script:documentPath = [IO.Path]::GetDirectoryName($fileName)
    $script:outputType   = Get-DocumentationOutputOption html "HTMLDocumentFileType" "Full"

    if ($script:outputType -eq "Object") {
        Write-Log "Document one file for each object + index file"
    }
    else {
        Write-Log "Document one single file for all objects"
        $script:outputType  = "Full"
        $script:htmlStrings = [System.Text.StringBuilder]::new()
    }
}

function Invoke-HTMLPostProcessItems {
    $userName = $null
    $mail     = ""
    $me = Get-CurrentUser
    if ($me) {
        if ($me.givenName -and $me.surname) {
            $userName = "$($me.givenName) $($me.surname)"
        }
        else {
            $userName = $me.displayName
        }
        if ($me.mail) { $mail = " ($($me.mail))" }
    }

    $orgName = Get-CurrentOrganizationName

    $title = Get-DocumentationOutputOption html "HTMLTitleProperty" "Intune documentation"
    if (-not $title) { $title = "Intune documentation" }

    $htmlContent = [System.Text.StringBuilder]::new()
    [void]$htmlContent.AppendLine("<HTML>")
    [void]$htmlContent.AppendLine($script:cssStyle)
    [void]$htmlContent.AppendLine("<H1 class='header-level1'>$title</H1>")

    if (-not ((Get-DocumentationOption "SkipDocumentInfo" $false) -eq $true)) {
        if ($orgName)  { [void]$htmlContent.AppendLine("Organization: $orgName<br />") }
        if ($userName) { [void]$htmlContent.AppendLine("Generated by: $userName$mail<br />") }
        [void]$htmlContent.AppendLine("Generated: $((Get-Date).ToShortDateString()) $((Get-Date).ToLongTimeString())<br />")
    }

    if ($script:sectionAnchors.Count -gt 0) {
        [void]$htmlContent.AppendLine("<br />")
        [void]$htmlContent.AppendLine("<H2 class='header-level2'>Table of Contents</H2>")
    }

    $tocMaxLevel = 4
    foreach ($header in $script:sectionAnchors) {
        if ($tocMaxLevel -gt 0 -and $header.Level -gt $tocMaxLevel) { continue }
        [void]$htmlContent.AppendLine("<a href='$($header.FileName)#$($header.Anchor)' class='anchor-style anchor-level$($header.Level)'>$($header.Name)</a><br />")
    }
    if ($script:sectionAnchors.Count -gt 0) { [void]$htmlContent.AppendLine("<br />") }

    $htmlText = $htmlContent.ToString()
    if ($script:outputType -eq "Full" -and $script:htmlStrings) {
        $htmlText += $script:htmlStrings.ToString()
    }
    $htmlText += "</HTML>"

    Save-DocumentationFile $htmlText $script:outFile -OpenFile:((Get-DocumentationOutputOption html "HTMLOpenFile" $true) -eq $true)
}

function Invoke-HTMLNewObjectGroup {
    param($groupId)
    $script:objectHeaderLevel = 2
    Add-HTMLHeader (Get-DocObjectTypeString $groupId)
}

function Invoke-HTMLNewObjectType {
    param($objectTypeName)
    $script:objectHeaderLevel = 3
    Add-HTMLHeader $objectTypeName
    $script:objectHeaderLevel = 4
}

