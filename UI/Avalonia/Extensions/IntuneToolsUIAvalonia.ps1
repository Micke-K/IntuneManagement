    }

    return $items
}

function Get-IntuneToolsItemIcon
{
    param([string]$IconName)

    $ui = $script:UIProvider
    # Icons live under UI/Avalonia/XAML/Icons/*.axaml (Avalonia-flavoured
    # ports of the WPF UI/WPF/XAML/Icons/*.xaml shape XAML, generated by
    # XAML/Icons/_Convert-Icons.ps1). Each is a Viewbox/Canvas/Path tree the
    # lstMenuItems ContentControl can host directly.
    if (-not $IconName) { return $null }
    $iconFile = Join-Path $script:AppUIRootFolder "XAML/Icons/$IconName.axaml"
    if (-not [IO.File]::Exists($iconFile)) { return $null }
    return ($ui.GetXamlObject($iconFile))
}

function Get-IntuneToolsViewPanel
{
    $ui = $script:UIProvider
    $panel = $ui.GetXamlObject((Join-Path $script:AppUIRootFolder 'XAML/IntuneTools.axaml'))
    if (-not $panel) { return $null }

    $script:grdToolsMain = (Get-AvaloniaHost)::FindByName($panel, 'grdToolsMain')
    return $panel
}

function Invoke-IntuneToolsActivateItem
{
    param($SelectedItem)

    if (-not $SelectedItem -or -not $script:grdToolsMain) { return $null }

    # WPF returned a CollectionViewGroup sentinel for group headers; the
    # Avalonia flat-list path doesn't surface those (yet).
    if (-not $SelectedItem.Id) {
        Write-Log "Unable to activate Intune tool. Selected item did not include a tool Id." 2
        return $null
    }

    Write-Log "Activate tool: $($SelectedItem.Title)"

    switch ($SelectedItem.Id)
    {
        'IntuneAssignments' { Show-IntuneAssignmentsTool }
        'IntuneFilterUsage' { Show-IntuneFilterUsageTool }
        'ADMXImport'        { Show-ADMXImportTool }
        'ADMXRegValues'     { Show-ADMXRegValuesTool }
        default
        {
            Write-Log "Unknown tool selected: $($SelectedItem.Id)" 2
            $script:grdToolsMain.Children.Clear()
        }
    }

    return $null
}

