# ─── ADMX Import tool — Slices 5a1+5a2+5a3+5a4 wired ─────────────────────────
#
# Avalonia port of UI/WPF/Extensions/IntuneToolsUI.ps1 Show-ADMXImportTool.
# Loads IntuneToolsADMX.axaml, caches every named control the WPF version
# uses, and wires every handler (Load ADMX / Load ADML / Import + Import-tab
# TextBox / CheckBox / Add-Random + DataGrid DoubleTap / context-menu Edit).
#
# Differences from WPF:
#  - WinForms OpenFileDialog -> (Get-AvaloniaHost)::OpenFilePicker (R13: this
#    project doesn't carry a WinForms / WindowsAPICodePack dependency in
#    UI/Avalonia/).
#  - The picker returns a string (or $null on cancel) rather than a DialogResult
#    + FileName pair, so the click handlers branch on truthiness.

function Show-ADMXImportTool
{
    $ui = $script:UIProvider
    if (-not $script:grdToolsMain) { return }
    $script:grdToolsMain.Children.Clear()

    $panel = $ui.GetXamlObject((Join-Path $script:AppUIRootFolder 'XAML/IntuneToolsADMX.axaml'))
    if (-not $panel) {
        Write-Log "Failed to load IntuneToolsADMX.axaml" 3
        Set-IntuneToolPlaceholder 'ADMX Import'
        return
    }

    # Cache panel + controls used by event handlers. FindByName once at panel-init
    # so click/select handlers don't re-probe the visual tree.
    $script:admxImportPanel           = $panel
    $script:btnADMXLoadADMX           = (Get-AvaloniaHost)::FindByName($panel, 'btnADMXLoadADMX')
    $script:btnADMXLoadADML           = (Get-AvaloniaHost)::FindByName($panel, 'btnADMXLoadADML')
    $script:btnADMXImport             = (Get-AvaloniaHost)::FindByName($panel, 'btnADMXImport')
    $script:btnADMXPolicyNameRandom   = (Get-AvaloniaHost)::FindByName($panel, 'btnADMXPolicyNameRandom')
    $script:tvADMXCategories          = (Get-AvaloniaHost)::FindByName($panel, 'tvADMXCategories')
    $script:dgADMXCategoryPolicies    = (Get-AvaloniaHost)::FindByName($panel, 'dgADMXCategoryPolicies')

    # The ADMX rows are PSCustomObjects, and Avalonia's binder cannot read
    # NoteProperties ({Binding Name} renders empty cells - see
    # [[avalonia-binding-needs-clr-types]]). Rebind each column through
    # IntunePolicyPathConverter with a self-binding (empty path = the row),
    # the same trick the main grid uses for ObjectColumns overrides.
    if ($script:dgADMXCategoryPolicies) {
        $admxPathConverter = (Get-AvaloniaHost)::CreatePathConverter()
        $admxColPaths = @('Name', 'SettingStatusText', 'Category')
        for ($i = 0; $i -lt [Math]::Min($admxColPaths.Count, $script:dgADMXCategoryPolicies.Columns.Count); $i++) {
            $b = New-Object Avalonia.Data.Binding ''
            $b.Mode               = [Avalonia.Data.BindingMode]::OneWay
            $b.Converter          = $admxPathConverter
            $b.ConverterParameter = $admxColPaths[$i]
            $script:dgADMXCategoryPolicies.Columns[$i].Binding = $b
        }
    }
    $script:txtADMXProfileName        = (Get-AvaloniaHost)::FindByName($panel, 'txtADMXProfileName')
    $script:txtADMXProfileDescription = (Get-AvaloniaHost)::FindByName($panel, 'txtADMXProfileDescription')
    $script:txtADMXPolicyFileName     = (Get-AvaloniaHost)::FindByName($panel, 'txtADMXPolicyFileName')
    $script:txtADMXPolicyAppName      = (Get-AvaloniaHost)::FindByName($panel, 'txtADMXPolicyAppName')
    $script:txtADMXPolicyIngestName   = (Get-AvaloniaHost)::FindByName($panel, 'txtADMXPolicyIngestName')
    $script:chkADMXPolicyIngest       = (Get-AvaloniaHost)::FindByName($panel, 'chkADMXPolicyIngest')

    # Per-tool state — initialised here so file-dialog handlers can write to it
    # without a null-check inside the click body.
    $script:currentADMXFile = $null

    # Idempotency for tree/grid event registration. Show-ADMXImportTool can be
    # called multiple times across nav switches; the cached panel persists in
    # memory for the lifetime of the IntuneTools view, so events shouldn't
    # double-register.
    $script:_admxImportEventsRegistered = $false

    $ui.AddXamlEvent($panel, 'btnADMXLoadADMX', 'add_Click', ({
        $startPath = Get-SettingStoreValue 'Tools' 'ADMXLastADMXFile'
        $picked = (Get-AvaloniaHost)::OpenFilePicker(
            $script:Window,
            'Select ADMX file',
            $startPath,
            'ADMX files',
            '*.admx')
        if ($picked) {
            $script:currentADMXFile = [IO.FileInfo]$picked
            Save-SettingStoreValue 'Tools' 'ADMXLastADMXFile' $picked
            Write-Status "Loading policy settings from $($script:currentADMXFile.Name)"
            Start-ADMXLoadFile $picked
            Write-Status ''
        }
    }))

    $ui.AddXamlEvent($panel, 'btnADMXLoadADML', 'add_Click', ({
        $startPath = Get-SettingStoreValue 'Tools' 'ADMXLastADMLFile'
        $picked = (Get-AvaloniaHost)::OpenFilePicker(
            $script:Window,
            'Select ADML file',
            $startPath,
            'ADML files',
            '*.adml')
        if ($picked) {
            Save-SettingStoreValue 'Tools' 'ADMXLastADMLFile' $picked
            Write-Status "Loading ADML policy $picked"
            Invoke-ADMXLoadSettings $picked
            Write-Status ''
        }
    }))

    $ui.AddXamlEvent($panel, 'btnADMXImport', 'add_Click', ({
        Write-Status 'Import ADMX policy'
        Import-ADMXPolicyToIntune
        Write-Status ''
    }))

    # Append-or-replace GUID suffix on the policy file name. The trailing
    # segment after "_" is the unique-id portion; if it's already a 32-char
    # GUID we leave the existing prefix alone and replace only the suffix.
    $ui.AddXamlEvent($panel, 'btnADMXPolicyNameRandom', 'add_Click', ({
        $guid = [Guid]::NewGuid().Guid
        if ($script:txtADMXPolicyFileName.Text) {
            $parts = $script:txtADMXPolicyFileName.Text.Split('_')
            if ($parts[-1].Length -eq $guid.Length) {
                $script:txtADMXPolicyFileName.Text = (($parts[0..($parts.Count - 2)] -join '_') + '_' + $guid)
            }
            else {
                $script:txtADMXPolicyFileName.Text = ($script:txtADMXPolicyFileName.Text + '_' + $guid)
            }
        }
        else {
            $script:txtADMXPolicyFileName.Text = $guid
        }
    }))

    $script:grdToolsMain.Children.Add($panel) | Out-Null
}

# ─── ADMX Import — helpers (data layer, pure functions) ───────────────────────
#
# Slice 5a2 — ports the ADMX/ADML parser + category-tree builder. Pure functions
# read $script:_admx* state set up by Start-ADMXLoadFile / Invoke-ADMXLoadSettings;
# none of them touch UI controls (the TreeViewItem renderer is the lone
# exception and is clearly named).
#
# Differences from WPF (UI/WPF/Extensions/IntuneToolsUI.ps1):
#  - Add-ADMXCategoryTreeNodeRecursive instantiates [Avalonia.Controls.TreeViewItem]
#    instead of [System.Windows.Controls.TreeViewItem]; the API surface used
#    (Header, Tag, Items.Add, Add-Member NoteProperty AllPolicies) carries over.

function Add-ADMXCategoriesRecursive
{
    param($Categories, $Parent, $SettingClass)

    foreach ($cat in $Categories.ref) {
        $catPath = Get-ADMXCategoryIdPath $cat
        $tvObj = $Parent
        foreach ($catName in $catPath.Split('/')) {
            $curParent = $tvObj.Children | Where-Object { $_.CategoryNode.name -eq $catName }
            if (-not $curParent) {
                $catNode = $script:_admxXML.policyDefinitions.categories.SelectSingleNode("$($script:_admxNSPrefix)category[@name='$catName']", $script:_admxNS)
                $curParent = [PSCustomObject]@{
                    Name         = Get-ADMXADMLString $catNode
                    CategoryName = $catName
                    CategoryNode = $catNode
                    SettingClass = $SettingClass
                    Children     = @()
                }
                $tvObj.Children += $curParent
            }
            $tvObj = $curParent
        }
    }
}

function Add-ADMXCategoryTreeNodeRecursive
{
    param($Obj, $Parent)

    $tvItem = [Avalonia.Controls.TreeViewItem]::new()
    $tvItem.Header = $Obj.Name
    $tvItem.Tag    = $Obj
    [void]$Parent.Items.Add($tvItem)

    $Obj.Children | Sort-Object -Property Name | ForEach-Object {
        Add-ADMXCategoryTreeNodeRecursive $_ $tvItem
    }
}

# ─── ADMX Import — loaders ────────────────────────────────────────────────────

function Start-ADMXLoadFile
{
    param($FileName)

    $ui = $script:UIProvider
    # Hard reset — partial state from a previous file would cross-contaminate
    # the tree-building below.
    $script:_admxNS            = $null
    $script:_admxNSPrefix      = $null
    $script:_admxXML           = $null
    $script:_admxPolicies      = @()
    $script:_admxPoliciesHT    = @{}
    $script:_admxSupportedOn   = @()
    $script:_admxCategoryPaths = @{}
    $script:_admxStringTable   = @{}
    $script:_admxlngADML       = $null

    if ($script:txtADMXProfileName)        { $script:txtADMXProfileName.Text        = '' }
    if ($script:txtADMXProfileDescription) { $script:txtADMXProfileDescription.Text = '' }
    if ($script:txtADMXPolicyFileName)     { $script:txtADMXPolicyFileName.Text     = '' }
    if ($script:txtADMXPolicyIngestName)   { $script:txtADMXPolicyIngestName.Text   = '' }
    if ($script:txtADMXPolicyAppName)      { $script:txtADMXPolicyAppName.Text      = '' }
    if ($script:btnADMXLoadADML)           { $script:btnADMXLoadADML.IsEnabled      = $false }

    $admxFI = [IO.FileInfo]$FileName
    if (-not $admxFI.Exists) {
        $ui.ShowMessageBox("ADMX file not found: $FileName", 'ADMX Import', 'OK', 'Error')
        return
    }

    # Convention: paired .adml lives in en-US\ next to the .admx, or sometimes
    # in the same folder. Missing ADML is a soft warning — Get-ADMXADMLString
    # falls back to raw attributes if so.
    $admlFile = [IO.Path]::Combine($admxFI.DirectoryName, "en-US", "$($admxFI.BaseName).adml")
    if (-not [IO.File]::Exists($admlFile)) {
        $admlFile = [IO.Path]::Combine($admxFI.DirectoryName, "$($admxFI.BaseName).adml")
    }
    if (-not [IO.File]::Exists($admlFile)) {
        Write-Log "Could not find an ADML file alongside $FileName" 2
        $admlFile = $null
    }

    try {
        Write-Log "Load ADMX file $FileName"
        [xml]$script:_admxXML = [IO.File]::ReadAllText($FileName)

        $namespace = $script:_admxXML.DocumentElement.NamespaceURI
        if ($namespace) {
            $script:_admxNS = New-Object System.Xml.XmlNamespaceManager($script:_admxXML.NameTable)
            $script:_admxNS.AddNamespace('ns', $namespace)
            $script:_admxNSPrefix = 'ns:'
        }
        else {
            $script:_admxNS       = $null
            $script:_admxNSPrefix = ''
        }

        # Default the App Id from the ADMX namespace prefix; fall back to the
        # filename if that's missing.
        $prefix = $script:_admxXML.policyDefinitions.policyNamespaces.SelectSingleNode("$($script:_admxNSPrefix)target[@prefix]", $script:_admxNS)
        $policyId = $null
        if ($prefix) {
            if ($prefix.namespace) { $policyId = $prefix.namespace.Split('.')[-1] }
            else                   { $policyId = $prefix.prefix }
        }
        if (-not $policyId) {
            $policyId = $admxFI.BaseName -replace ' ', ''
            Write-Log 'Failed to get policy id from ADMX namespace; using file base name' 2
        }
        if ($script:txtADMXPolicyAppName)  { $script:txtADMXPolicyAppName.Text  = $policyId }
        if ($script:txtADMXPolicyFileName) { $script:txtADMXPolicyFileName.Text = $policyId }
    }
    catch {
        Write-LogError 'Failed to load ADMX file' $_.Exception
        return
    }

    if ($script:btnADMXLoadADML) { $script:btnADMXLoadADML.IsEnabled = $true }
    Invoke-ADMXLoadSettings $admlFile
}

function Invoke-ADMXLoadSettings
{
    param($AdmlFile)

    if ($AdmlFile -and [IO.File]::Exists($AdmlFile)) {
        try {
            Write-Log "Load ADML file $AdmlFile"
            [xml]$script:_admxlngADML = [IO.File]::ReadAllText($AdmlFile)
        }
        catch {
            Write-LogError "Failed to load ADML file $AdmlFile" $_.Exception
        }
    }

    $script:_admxStringTable = @{}
    if ($script:_admxlngADML) {
        foreach ($strNode in $script:_admxlngADML.policyDefinitionResources.resources.stringTable.string) {
            if (-not $script:_admxStringTable.ContainsKey($strNode.id)) {
                $script:_admxStringTable.Add($strNode.id, $strNode.'#text')
            }
        }
    }

    # supportedOn table — augmented with Windows.adml's SUPPORTED_* entries so
    # policies that reference common Windows constants still resolve in the
    # SettingProperties dialog (slice 5a3).
    $script:_admxSupportedOn = @()
    foreach ($polObj in $script:_admxXML.policyDefinitions.supportedOn.definitions.definition) {
        $script:_admxSupportedOn += [PSCustomObject]@{
            Id          = $polObj.Name
            DisplayName = (Get-ADMXADMLString $polObj)
        }
    }
    if ($script:_admxWindowsADML) {
        foreach ($winString in ($script:_admxWindowsADML.policyDefinitionResources.resources.stringTable.string | Where-Object Id -like 'SUPPORTED_*')) {
            $script:_admxSupportedOn += [PSCustomObject]@{
                Id          = $winString.id
                DisplayName = $winString.'#text'
            }
        }
    }

    $devicePolicies = @()
    $userPolicies   = @()

    foreach ($polObj in $script:_admxXML.policyDefinitions.policies.policy) {
        $category    = if ($polObj.parentCategory.ref) { Get-ADMXCategoryNamePath $polObj.parentCategory.ref '/' } else { $null }
        $displayName = Get-ADMXADMLString $polObj
        $description = Get-ADMXADMLString $polObj 'explainText'

        # Class can be Both / Machine / User. "Both" expands into two virtual
        # entries so it shows up in both Device + User configuration trees.
        $classArr = switch ($polObj.Class) {
            'Both'    { @('Device','User') }
            'Machine' { @('Device') }
            default   { @($polObj.Class) }
        }

        foreach ($class in $classArr) {
            $key = "$($polObj.Name)_$class"
            if ($script:_admxPoliciesHT.ContainsKey($key)) { continue }

            $newSetting = [PSCustomObject]@{
                Name              = $displayName
                Description       = $description
                OMAURIName        = $null
                OMAURIDescription = $null
                Category          = $category
                CategoryId        = $polObj.parentCategory.ref
                Id                = $polObj.Name
                Definition        = $polObj
                SettingStatus     = $null
                SettingStatusText = $null
                PolicySettings    = $null
                PolicyDefinition  = $null
                ElementsPanel     = $null
                ManualConfig      = $false
                SettingClass      = $class
                SupportedOn       = $null
            }
            $script:_admxPoliciesHT.Add($key, $newSetting)
            $script:_admxPolicies   += $newSetting
            if ($class -eq 'User') { $userPolicies   += $newSetting }
            else                   { $devicePolicies += $newSetting }
        }
    }

    $script:_admxPolicies | ForEach-Object { Set-ADMXSettingStatusText $_ }
    $script:_admxPolicies = $script:_admxPolicies | Sort-Object -Property Name

    if ($script:tvADMXCategories) { $script:tvADMXCategories.Items.Clear() }

    $treeItems = @()

    # Device Configuration root
    $tvItem = [PSCustomObject]@{ Name = 'Computer Configuration'; Children = @() }
    if ($script:_admxXML.policyDefinitions.policies) {
        $policies = $script:_admxXML.policyDefinitions.policies.SelectNodes("$($script:_admxNSPrefix)policy[@class = 'Both' or @class = 'Machine']", $script:_admxNS)
        if ($policies) {
            $categories = $policies.parentCategory | Select-Object ref -Unique
            Add-ADMXCategoriesRecursive $categories $tvItem 'Device'
        }
    }
    $treeItems += $tvItem

    # User Configuration root
    $tvItem = [PSCustomObject]@{ Name = 'User Configuration'; Children = @() }
    if ($script:_admxXML.policyDefinitions.policies) {
        $policies = $script:_admxXML.policyDefinitions.policies.SelectNodes("$($script:_admxNSPrefix)policy[@class = 'Both' or @class = 'User']", $script:_admxNS)
        if ($policies) {
            $categories = $policies.parentCategory | Select-Object ref -Unique
            Add-ADMXCategoriesRecursive $categories $tvItem 'User'
        }
    }
    $treeItems += $tvItem

    $treeItems | ForEach-Object { Add-ADMXCategoryTreeNodeRecursive $_ $script:tvADMXCategories }

    # "All Policies" leaf under each root — quick way to see everything.
    if ($devicePolicies.Count -gt 0 -and $script:tvADMXCategories.Items.Count -ge 1) {
        $tv = [Avalonia.Controls.TreeViewItem]::new()
        $tv.Header = 'All Policies'
        $tv.Tag    = $devicePolicies
        $tv | Add-Member -MemberType NoteProperty -Name 'AllPolicies' -Value $true
        [void]$script:tvADMXCategories.Items[0].Items.Add($tv)
    }
    if ($userPolicies.Count -gt 0 -and $script:tvADMXCategories.Items.Count -ge 2) {
        $tv = [Avalonia.Controls.TreeViewItem]::new()
        $tv.Header = 'All Policies'
        $tv.Tag    = $userPolicies
        $tv | Add-Member -MemberType NoteProperty -Name 'AllPolicies' -Value $true
        try { [void]$script:tvADMXCategories.Items[1].Items.Add($tv) } catch { }
    }

    Register-ADMXImportTreeEvents
}

function Register-ADMXImportTreeEvents
{
    # Idempotent — only registers once per panel lifetime. ScriptBlocks read
    # $script: state, so they work the same across reloads of ADMX files.
    if ($script:_admxImportEventsRegistered) { return }
    $script:_admxImportEventsRegistered = $true

    if ($script:tvADMXCategories) {
        # WPF SelectedItemChanged -> Avalonia SelectionChanged on TreeView
        # (TreeView extends SelectingItemsControl; raises SelectionChanged when
        # the selected node changes).
        $script:tvADMXCategories.add_SelectionChanged((ConvertTo-AvaloniaEventScriptBlock {
            $sel = $script:tvADMXCategories.SelectedItem
            if (-not $sel) { return }

            # When Items were populated with TreeViewItem instances directly,
            # SelectedItem is the TreeViewItem itself; .Tag carries our model.
            $hasAllPolicies = ($sel.PSObject.Properties['AllPolicies']) -and $sel.AllPolicies -eq $true

            if ($hasAllPolicies) {
                $script:dgADMXCategoryPolicies.Columns[0].Width    = [Avalonia.Controls.DataGridLength]::Auto
                $script:dgADMXCategoryPolicies.Columns[1].Width    = [Avalonia.Controls.DataGridLength]::Auto
                $script:dgADMXCategoryPolicies.Columns[2].Width    = [Avalonia.Controls.DataGridLength]::Auto
                $script:dgADMXCategoryPolicies.Columns[2].IsVisible = $true
                $list = $sel.Tag
            }
            else {
                $script:dgADMXCategoryPolicies.Columns[0].Width    = [Avalonia.Controls.DataGridLength]::new(1, [Avalonia.Controls.DataGridLengthUnitType]::Star)
                $script:dgADMXCategoryPolicies.Columns[1].Width    = [Avalonia.Controls.DataGridLength]::Auto
                $script:dgADMXCategoryPolicies.Columns[2].IsVisible = $false
                $list = @($script:_admxPolicies | Where-Object {
                    $_.CategoryId   -eq $sel.Tag.CategoryName -and
                    $_.SettingClass -eq $sel.Tag.SettingClass
                })
            }
            $script:dgADMXCategoryPolicies.ItemsSource = [System.Collections.ObjectModel.ObservableCollection[object]]::new(@($list))
        }))
    }

    if ($script:dgADMXCategoryPolicies) {
        # WPF MouseDoubleClick -> Avalonia DoubleTapped (per established pattern).
        $script:dgADMXCategoryPolicies.add_DoubleTapped((ConvertTo-AvaloniaEventScriptBlock {
            if (-not $script:dgADMXCategoryPolicies.SelectedItem) { return }
            Show-ADMXSettingPropertiesDialog $script:dgADMXCategoryPolicies.SelectedItem
        }))

        $mnu = $script:dgADMXCategoryPolicies.ContextMenu
        if ($mnu) {
            # Avalonia ContextMenu has Opening (cancellable) but the WPF Opened-
            # to-toggle-IsEnabled pattern is fragile here anyway; the click
            # handler already returns early if there's no SelectedItem, so no
            # menu-open hook is needed.
            $edit = $mnu.Items | Where-Object Name -eq 'mnuADMXSettingEdit' | Select-Object -First 1
            if ($edit) {
                $edit.add_Click((ConvertTo-AvaloniaEventScriptBlock {
                    if ($script:dgADMXCategoryPolicies.SelectedItem) {
                        Show-ADMXSettingPropertiesDialog $script:dgADMXCategoryPolicies.SelectedItem
                    }
                }))
            }
        }
    }

    # Pre-load Windows.adml for SUPPORTED_* string resolution (best-effort).
    if (-not $script:_admxWindowsADML) {
        $winADML = "$($env:WinDir)\PolicyDefinitions\en-US\Windows.adml"
        if ([IO.File]::Exists($winADML)) {
            try { [xml]$script:_admxWindowsADML = [IO.File]::ReadAllText($winADML) }
            catch { Write-LogDebug "Failed to load Windows.adml: $($_.Exception.Message)" }
        }
    }
}

# ─── ADMX Import — SettingProperties dialog (Slice 5a3) ──────────────────────
#
# Avalonia port of Show-ADMXSettingPropertiesDialog + Set-ADMXSettingProperties +
# Set-ADMXElementsPanel + Save-ADMXSettings + Get-ADMXSettingsString from
# UI/WPF/Extensions/IntuneToolsUI.ps1. Differences from WPF:
#  - {Binding ...} on PSCustomObject doesn't render in Avalonia. Form fields
#    that bound to SupportedOn / Description / PolicyDefinition are now named
#    TextBoxes; Set-ADMXSettingProperties pushes values imperatively.
#  - WPF NumericUpDown.xaml replaced with [Avalonia.Controls.NumericUpDown];
#    Get-ADMXSettingsString reads .Value directly (no .Children[0].Text dance).
#  - WPF [System.Windows.LogicalTreeHelper]::FindLogicalNode replaced with a
#    flat scan of $Item.ElementsPanel.Children by .Name (the elements grid is
#    only one level deep so iteration is fine).
#  - WPF DataGrid.CanUserAddRows is missing in Avalonia 11; listBox elements
#    get inline Add / Remove buttons after the DataGrid so users can build
#    the rows themselves.
#  - WPF CollectionViewSource.GetDefaultView(...).Refresh() has no Avalonia
#    equivalent; rebuild the ItemsSource ObservableCollection instead so the
#    single edited row's status text updates.

function Show-ADMXSettingPropertiesDialog
{
    param($SettingObj)
    $ui = $script:UIProvider
    if (-not $SettingObj) { return }

    $form = $ui.GetXamlObject((Join-Path $script:AppUIRootFolder 'XAML/IntuneToolsADMXSettingProperties.axaml'))
    if (-not $form) { return }

    $script:_admxSettingsForm        = $form
    $script:_admxLblSettingName      = (Get-AvaloniaHost)::FindByName($form, 'lblADMXSettingName')
    $script:_admxGrdElements         = (Get-AvaloniaHost)::FindByName($form, 'grdADMXElements')
    $script:_admxRbEnabled           = (Get-AvaloniaHost)::FindByName($form, 'rbADMXSettingEnabled')
    $script:_admxRbDisabled          = (Get-AvaloniaHost)::FindByName($form, 'rbADMXSettingDisabled')
    $script:_admxRbNotConfigured     = (Get-AvaloniaHost)::FindByName($form, 'rbADMXSettingNotConfigured')
    $script:_admxTxtSettings         = (Get-AvaloniaHost)::FindByName($form, 'txtADMXSettings')
    $script:_admxTxtSettingName      = (Get-AvaloniaHost)::FindByName($form, 'txtADMXSettingName')
    $script:_admxTxtSettingComment   = (Get-AvaloniaHost)::FindByName($form, 'txtADMXSettingComment')
    $script:_admxTxtSupportedOn      = (Get-AvaloniaHost)::FindByName($form, 'txtADMXSupportedOn')
    $script:_admxTxtDescription      = (Get-AvaloniaHost)::FindByName($form, 'txtADMXSettingDescription')
    $script:_admxTxtPolicyDefinition = (Get-AvaloniaHost)::FindByName($form, 'txtADMXPolicyDefinition')
    $script:_admxChkManualConfig     = (Get-AvaloniaHost)::FindByName($form, 'chkADMXManualConfig')
    $script:_admxBtnPrev             = (Get-AvaloniaHost)::FindByName($form, 'btnADMXPreviousSetting')
    $script:_admxBtnNext             = (Get-AvaloniaHost)::FindByName($form, 'btnADMXNextSetting')
    $script:_admxTcPolicyConfig      = (Get-AvaloniaHost)::FindByName($form, 'tcADMXPolicyConfig')
    $script:_admxTabSettings         = (Get-AvaloniaHost)::FindByName($form, 'tabADMXSettings')

    Set-ADMXSettingProperties $SettingObj
    Set-ADMXSettingButtonsStatus

    $ui.AddXamlEvent($form, 'btnADMXSettingsOK', 'Add_Click', ({
        Save-ADMXSettings
        Show-ModalObject
    }))

    # Capture the index BEFORE Save-ADMXSettings: it rebuilds the grid's
    # ItemsSource (its refresh mechanism), which resets SelectedIndex to -1 -
    # reading the index afterwards navigated to an invalid row and the dialog
    # silently stayed put.
    $ui.AddXamlEvent($form, 'btnADMXPreviousSetting', 'Add_Click', ({
        $idx = $script:dgADMXCategoryPolicies.SelectedIndex
        if ($idx -le 0) { return }
        Save-ADMXSettings
        $script:dgADMXCategoryPolicies.SelectedIndex = $idx - 1
        Set-ADMXSettingButtonsStatus
        Set-ADMXSettingProperties $script:dgADMXCategoryPolicies.SelectedItem
    }))

    $ui.AddXamlEvent($form, 'btnADMXNextSetting', 'Add_Click', ({
        $idx = $script:dgADMXCategoryPolicies.SelectedIndex
        $count = @($script:dgADMXCategoryPolicies.ItemsSource).Count
        if ($idx -lt 0 -or $idx -ge ($count - 1)) { return }
        Save-ADMXSettings
        $script:dgADMXCategoryPolicies.SelectedIndex = $idx + 1
        Set-ADMXSettingButtonsStatus
        Set-ADMXSettingProperties $script:dgADMXCategoryPolicies.SelectedItem
    }))

    $ui.AddXamlEvent($form, 'btnADMXSettingsCancel', 'Add_Click', ({
        if ($script:_admxGrdElements) { $script:_admxGrdElements.Children.Clear() }
        $script:_admxSettingsForm = $null
        Show-ModalObject
    }))

    # WPF used Add_Checked on each RadioButton; Avalonia ToggleButton fires
    # IsCheckedChanged regardless of direction, so we gate on IsChecked inside.
    $script:_admxRbEnabled.add_IsCheckedChanged((ConvertTo-AvaloniaEventScriptBlock {
        if ($script:_admxRbEnabled.IsChecked -eq $true) {
            $script:_admxCurItemStatus = 1
            Set-ADMXControlStatus
        }
    }))
    $script:_admxRbDisabled.add_IsCheckedChanged((ConvertTo-AvaloniaEventScriptBlock {
        if ($script:_admxRbDisabled.IsChecked -eq $true) {
            $script:_admxCurItemStatus = 0
            Set-ADMXControlStatus
        }
    }))
    $script:_admxRbNotConfigured.add_IsCheckedChanged((ConvertTo-AvaloniaEventScriptBlock {
        if ($script:_admxRbNotConfigured.IsChecked -eq $true) {
            $script:_admxCurItemStatus = $null
            Set-ADMXControlStatus
        }
    }))

    $script:_admxChkManualConfig.add_Click((ConvertTo-AvaloniaEventScriptBlock { Set-ADMXControlStatus }))

    $script:_admxTcPolicyConfig.add_SelectionChanged((ConvertTo-AvaloniaEventScriptBlock {
        param($S, $E)
        if ($E.AddedItems.Count -eq 0) { return }
        if ($E.AddedItems[0] -eq $script:_admxTabSettings -and
            $script:dgADMXCategoryPolicies.SelectedItem -and
            $script:dgADMXCategoryPolicies.SelectedItem.ManualConfig -ne 1) {
            $script:_admxTxtSettings.Text = Get-ADMXSettingsString $script:dgADMXCategoryPolicies.SelectedItem
        }
    }))

    $ui.ShowModalForm($SettingObj.Name, $form, $true)
}

