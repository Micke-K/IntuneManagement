# ─── Intune Assignments tool ──────────────────────────────────────────────────
#
# Avalonia port of UI/WPF/Extensions/IntuneToolsUI.ps1 Show-IntuneAssignmentsTool.
# Notable differences vs WPF:
#  - PSCustomObject rows from Get-IntuneAssignmentRow are converted to
#    [IntuneAssignmentRowItem] CLR instances before the DataGrid sees them
#    (Avalonia's binder can't read PSObject NoteProperty).
#  - Provider ComboBox uses ItemTemplate {Binding Name} instead of WPF
#    DisplayMemberPath; SelectedItem.Value substitutes for SelectedValuePath.
#  - Filter rebuilds an ItemsSource subset rather than using WPF's
#    ICollectionView.Items.Filter (Avalonia DataGrid doesn't expose that).
#  - Folder-options panel doesn't use DataContext binding (provider classes
#    don't implement INPC); Register-IntuneAssignmentsProviderEvents sets
#    TextBox.Text imperatively and wires TextChanged + Browse to push back.
#  - Save button goes through (Get-AvaloniaHost)::SaveFilePicker instead of
#    WinForms SaveFileDialog (R13 — WindowsAPICodePack lives only in UI/).

function Show-IntuneAssignmentsTool
{
    $ui = $script:UIProvider
    if (-not $script:grdToolsMain) { return }
    $script:grdToolsMain.Children.Clear()

    $panel = $ui.GetXamlObject((Join-Path $script:AppUIRootFolder 'XAML/IntuneToolsAssignments.axaml'))
    if (-not $panel) {
        Write-Log "Failed to load IntuneToolsAssignments.axaml" 3
        Set-IntuneToolPlaceholder 'Intune Assignments'
        return
    }

    $script:intuneAssignmentsPanel              = $panel
    $script:intuneAssignmentsProviderPanelCache = @{}
    # Keep last-loaded rows across panel rebuilds so the user doesn't have to
    # re-run the load every time they navigate away from and back to the tool.
    if (-not $script:intuneAssignmentsRows) { $script:intuneAssignmentsRows = @() }

    $script:cbIntuneAssignmentsProvider        = (Get-AvaloniaHost)::FindByName($panel, 'cbIntuneAssignmentsProvider')
    $script:ccIntuneAssignmentsProviderOptions = (Get-AvaloniaHost)::FindByName($panel, 'ccIntuneAssignmentsProviderOptions')
    $script:dgIntuneAssignments                = (Get-AvaloniaHost)::FindByName($panel, 'dgIntuneAssignments')
    $script:txtIntuneAssignmentsFilter         = (Get-AvaloniaHost)::FindByName($panel, 'txtIntuneAssignmentsFilter')
    $script:txtIntuneAssignmentsCount          = (Get-AvaloniaHost)::FindByName($panel, 'txtIntuneAssignmentsCount')
    $script:cbIntuneAssignmentsView            = (Get-AvaloniaHost)::FindByName($panel, 'cbIntuneAssignmentsView')

    if ($script:cbIntuneAssignmentsProvider) {
        $script:cbIntuneAssignmentsProvider.ItemsSource = @($script:intuneAssignmentsProviders)

        # DisplayMemberPath -> ItemTemplate binding (Avalonia ComboBox has no
        # DisplayMemberPath property).

        # Restore previously-selected provider. SelectedValuePath doesn't exist
        # in Avalonia ComboBox; match by .Value on the source list.
        $savedValue = Get-SettingStoreValue 'IntuneAssignments' 'Provider' 'folder'
        $selected = $script:intuneAssignmentsProviders | Where-Object { $_.Value -eq $savedValue } | Select-Object -First 1
        if (-not $selected -and $script:intuneAssignmentsProviders.Count -gt 0) {
            $selected = $script:intuneAssignmentsProviders[0]
        }
        if ($selected) { $script:cbIntuneAssignmentsProvider.SelectedItem = $selected }

        # Run the options-panel switch synchronously once before wiring the
        # event handler, so the initial Set fires exactly once.
        Set-IntuneAssignmentsProviderOptions $script:cbIntuneAssignmentsProvider

        $script:cbIntuneAssignmentsProvider.add_SelectionChanged((ConvertTo-AvaloniaEventScriptBlock {
            param($S, $E)
            Set-IntuneAssignmentsProviderOptions $S
        }))
    }

    $ui.AddXamlEvent($panel, 'btnGetIntuneAssignments', 'Add_Click', ({
        Start-IntuneAssignmentsLoad
    }))

    $ui.AddXamlEvent($panel, 'btnIntuneAssignmentsCopy', 'Add_Click', ({
        $items = @(Get-IntuneToolsDataGridVisibleItems $script:dgIntuneAssignments)
        if ($items.Count -eq 0) { return }
        ($items | Select-Object Name, Type, AssignmentCount, HasFilters, IncludedString, ExcludedString, IncludedFilterString, ExcludedFilterString | ConvertTo-Csv -NoTypeInformation) | Set-Clipboard
    }))

    $ui.AddXamlEvent($panel, 'btnIntuneAssignmentsSave', 'Add_Click', ({
        $items = @(Get-IntuneToolsDataGridVisibleItems $script:dgIntuneAssignments)
        if ($items.Count -eq 0) { return }

        $initialName = "IntuneAssignments_$((Get-Date).ToString('yyyyMMdd-HHmm'))"
        # Reopen at the folder used last (WPF sets InitialDirectory); the
        # setting was written on every save but never read back.
        $lastDir = Get-SettingStoreValue 'IntuneAssignments' 'LastSaveDirectory'
        if (-not $lastDir) { $lastDir = Get-SettingValue 'RootFolder' }
        $picked = (Get-AvaloniaHost)::SaveFilePicker(
            $script:Window,
            'Save assignments',
            $initialName,
            'csv',
            'CSV files',
            '*.csv',
            [string]$lastDir)

        if ($picked) {
            Save-SettingStoreValue 'IntuneAssignments' 'LastSaveDirectory' ([IO.FileInfo]$picked).DirectoryName
            ($items | Select-Object Name, Type, AssignmentCount, HasFilters, IncludedString, ExcludedString, IncludedFilterString, ExcludedFilterString | ConvertTo-Csv -NoTypeInformation) | Out-File -LiteralPath $picked -Force -Encoding UTF8
        }
    }))

    $ui.AddXamlEvent($panel, 'txtIntuneAssignmentsFilter', 'Add_TextChanged', ({
        Update-IntuneAssignmentsFilter
    }))

    if ($script:cbIntuneAssignmentsView) {
        # Wrap in the CLR combo type - a PSCustomObject would bind blank here.
        $viewItems = [System.Collections.Generic.List[NameValueComboItem]]::new()
        foreach ($option in (Get-IntuneAssignmentViewOptions)) {
            [void]$viewItems.Add([NameValueComboItem]@{ Name = $option.Name; Value = $option.Value; Source = $option })
        }
        $script:cbIntuneAssignmentsView.ItemsSource = $viewItems
        # First option (Show all) is the default.
        $script:cbIntuneAssignmentsView.SelectedIndex = 0

        $script:cbIntuneAssignmentsView.add_SelectionChanged((ConvertTo-AvaloniaEventScriptBlock {
            param($S, $E)
            Update-IntuneAssignmentsFilter
        }))
    }

    if (@($script:intuneAssignmentsRows).Count -gt 0 -and $script:dgIntuneAssignments) {
        $script:dgIntuneAssignments.ItemsSource = $script:intuneAssignmentsRows
        Update-IntuneAssignmentsFilter
    }

    $script:grdToolsMain.Children.Add($panel) | Out-Null
}

function Set-IntuneAssignmentsProviderOptions
{
    param($Control)

    $ui = $script:UIProvider
    if (-not $Control) { return }
    $Provider = $Control.SelectedItem
    if (-not $Provider) { return }

    Save-SettingStoreValue 'IntuneAssignments' 'Provider' $Provider.Value

    $providerPanel = $null
    if ($Provider.OptionsXaml) {
        if ($script:intuneAssignmentsProviderPanelCache.ContainsKey($Provider.Value)) {
            $providerPanel = $script:intuneAssignmentsProviderPanelCache[$Provider.Value]
        } else {
            $panelPath = Join-Path $script:AppUIRootFolder "XAML/$($Provider.OptionsXaml).axaml"
            if (Test-Path -LiteralPath $panelPath) {
                $providerPanel = $ui.GetXamlObject($panelPath)
                if ($providerPanel) {
                    $script:intuneAssignmentsProviderPanelCache[$Provider.Value] = $providerPanel
                    Register-IntuneAssignmentsProviderEvents $providerPanel $Provider
                }
            } else {
                Write-Log "Provider options panel not found: $panelPath" 3
            }
        }
    }

    if ($script:ccIntuneAssignmentsProviderOptions) {
        $script:ccIntuneAssignmentsProviderOptions.Content   = $providerPanel
        $script:ccIntuneAssignmentsProviderOptions.IsVisible = [bool]$providerPanel
    }
}

function Register-IntuneAssignmentsProviderEvents
{
    param($Panel, $Provider)

    $ui = $script:UIProvider
    if ($Provider -is [IntuneAssignmentsFolderProvider]) {
        $Provider.ExportPath = Get-SettingStoreValue 'IntuneAssignments' 'ExportPath'

        $txtPath = (Get-AvaloniaHost)::FindByName($Panel, 'txtIntuneAssignmentsExportPath')
        if ($txtPath) {
            $txtPath.Text = [string]$Provider.ExportPath
            # Two-way sync: typing pushes into Provider.ExportPath. No INPC needed.
            $txtPath.Tag = $Provider
            $txtPath.add_TextChanged((ConvertTo-AvaloniaEventScriptBlock {
                param($S, $E)
                if ($S.Tag) { $S.Tag.ExportPath = [string]$S.Text }
            }))
        }

        $browse = (Get-AvaloniaHost)::FindByName($Panel, 'browseIntuneAssignmentsExportPath')
        if ($browse -and $txtPath) {
            $browse.Tag = @{ Provider = $Provider; TextBox = $txtPath }
            $browse.add_Click((ConvertTo-AvaloniaEventScriptBlock {
                param($S, $E)
                $tag = $S.Tag
                # $script:UIProvider by name - a captured function-local $ui is
                # stripped by ConvertTo-AvaloniaEventScriptBlock (closure law).
                # Start the picker at the current path like WPF does.
                $folder = $script:UIProvider.ShowFolderPicker([string]$tag.Provider.ExportPath, 'Select root folder for exported objects')
                if ($folder) {
                    $tag.Provider.ExportPath = $folder
                    $tag.TextBox.Text        = $folder   # TextChanged will refresh Provider again — harmless
                }
            }))
        }
    }
}

function Start-IntuneAssignmentsLoad
{
    $ui = $script:UIProvider
    if (-not $script:cbIntuneAssignmentsProvider) { return }

    $provider = $script:cbIntuneAssignmentsProvider.SelectedItem
    if (-not $provider) {
        $ui.ShowMessageBox('Select an input source first', 'Intune Assignments', 'OK', 'Error')
        return
    }

    try {
        if (-not $provider.Validate()) { return }

        $provider.SaveSettings()

        Write-Status 'Get Intune assignments'

        $script:dgIntuneAssignments.ItemsSource = $null
        $rawRows = @($provider.GetAssignments())

        # Coerce each PSCustomObject row into a CLR class instance so Avalonia
        # bindings (Name / Type / HasFilters / ...) resolve.
        $rows = @($rawRows | ForEach-Object {
            if (-not $_) { return }
            [IntuneAssignmentRowItem]@{
                Name                 = [string]$_.Name
                Type                 = [string]$_.Type
                AssignmentCount      = [int]$_.AssignmentCount
                HasFilters           = [bool]$_.HasFilters
                IncludedString       = [string]$_.IncludedString
                ExcludedString       = [string]$_.ExcludedString
                IncludedFilterString = [string]$_.IncludedFilterString
                ExcludedFilterString = [string]$_.ExcludedFilterString
                Id                   = [string]$_.Id
                Object               = $_.Object
                Included             = @($_.Included)
                Excluded             = @($_.Excluded)
                IncludedFilters      = @($_.IncludedFilters)
                ExcludedFilters      = @($_.ExcludedFilters)
            }
        })

        $script:intuneAssignmentsRows = $rows
        Update-IntuneAssignmentsFilter   # sets ItemsSource + summary
    } catch {
        $ui.ShowMessageBox($_.Exception.Message, 'Intune Assignments', 'OK', 'Error')
    } finally {
        Write-Status ''
    }
}

function Get-IntuneAssignmentsSelectedView
{
    # Value of the View combo, defaulting to All before the panel is built.
    if (-not $script:cbIntuneAssignmentsView) { return 'All' }
    $value = "$($script:cbIntuneAssignmentsView.SelectedItem.Value)"
    if ([string]::IsNullOrEmpty($value)) { return 'All' }
    return $value
}

function Update-IntuneAssignmentsFilter
{
    if (-not $script:dgIntuneAssignments) { return }
    if (-not $script:txtIntuneAssignmentsFilter) { return }

    $text = "$($script:txtIntuneAssignmentsFilter.Text)".Trim()
    $view = Get-IntuneAssignmentsSelectedView

    $script:dgIntuneAssignments.ItemsSource = $null

    if ([string]::IsNullOrEmpty($text) -and $view -eq 'All') {
        $script:dgIntuneAssignments.ItemsSource = $script:intuneAssignmentsRows
    } else {
        $pattern = [regex]::Escape($text)
        # Where-Object pipes items as PSObject wrappers; Avalonia's DataGrid
        # text-column binder reflects on the runtime type and silently fails
        # against the wrapper. Collect into a typed List so rows stay as
        # bare IntuneAssignmentRowItem instances.
        $filtered = [System.Collections.Generic.List[IntuneAssignmentRowItem]]::new()
        foreach ($row in $script:intuneAssignmentsRows) {
            if (-not (Test-IntuneAssignmentViewMatch $row $view)) { continue }
            if ([string]::IsNullOrEmpty($text)) { [void]$filtered.Add($row); continue }
            if (
                ($row.Name                 -and $row.Name                 -match $pattern) -or
                ($row.Type                 -and $row.Type                 -match $pattern) -or
                ($row.IncludedString       -and $row.IncludedString       -match $pattern) -or
                ($row.ExcludedString       -and $row.ExcludedString       -match $pattern) -or
                ($row.IncludedFilterString -and $row.IncludedFilterString -match $pattern) -or
                ($row.ExcludedFilterString -and $row.ExcludedFilterString -match $pattern) -or
                ($row.HasFilters           -and 'Has filters'             -match $pattern)
            ) {
                [void]$filtered.Add($row)
            }
        }
        $script:dgIntuneAssignments.ItemsSource = $filtered
    }

    Update-IntuneAssignmentsSummary
}

function Update-IntuneAssignmentsSummary
{
    if (-not $script:txtIntuneAssignmentsCount) { return }
    $total   = @($script:intuneAssignmentsRows).Count
    $visible = @($script:dgIntuneAssignments.ItemsSource).Count
    $script:txtIntuneAssignmentsCount.Text =
        if ($total -eq $visible) { "$total objects" } else { "$visible of $total objects" }
}

function Get-IntuneToolsDataGridVisibleItems
{
    param($DataGrid)
    if (-not $DataGrid -or -not $DataGrid.ItemsSource) { return @() }
    return @($DataGrid.ItemsSource)
}

