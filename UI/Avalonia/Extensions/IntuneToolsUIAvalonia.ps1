function Start-IntuneFilterUsageLoad
{
    $ui = $script:UIProvider
    if (-not $script:dgIntuneFilterUsage) { return }

    if ($script:btnGetIntuneFilterUsage) { $script:btnGetIntuneFilterUsage.IsEnabled = $false }

    try {
        # Reset per-load lazy caches so a re-run picks up fresh server state.
        $script:_intuneEnrollmentConfigCache = $null
        $script:_intuneManagedAppPolicyCache = $null

        Write-Status 'Get Intune filter usage'

        $script:dgIntuneFilterUsage.ItemsSource = $null
        try {
            $rawRows = @(Get-IntuneFilterUsageData)
        } catch {
            Write-LogError 'Intune Filter Usage: load failed' $_.Exception
            Write-Status ''
            $ui.ShowMessageBox("Failed to load filter usage:`n`n$($_.Exception.Message)", 'Intune Filter Usage', 'OK', 'Error')
            return
        }

        # PSCustomObject -> CLR class for Avalonia binding.
        $rows = @($rawRows | ForEach-Object {
            if (-not $_) { return }
            [IntuneFilterUsageRowItem]@{
                FilterName  = [string]$_.FilterName
                Platform    = [string]$_.Platform
                FilterType  = [string]$_.FilterType
                PolicyName  = [string]$_.PolicyName
                PayloadType = [string]$_.PayloadType
                Mode        = [string]$_.Mode
                GroupId     = [string]$_.GroupId
                GroupName   = [string]$_.GroupName
            }
        })

        $script:intuneFilterUsageRows = $rows
        Update-IntuneFilterUsageFilter   # sets ItemsSource + summary

        Write-Status ''
    } finally {
        if ($script:btnGetIntuneFilterUsage) { $script:btnGetIntuneFilterUsage.IsEnabled = $true }
    }
}

