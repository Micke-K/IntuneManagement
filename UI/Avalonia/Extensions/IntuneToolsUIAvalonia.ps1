function Set-ADMXSettingProperties
{
    param($SettingObj)
    if (-not $SettingObj) { return }

    $script:_admxGrdElements.Children.Clear()
    $script:_admxCurItemStatus = $SettingObj.SettingStatus

    switch ($SettingObj.SettingStatus) {
        0       { $script:_admxRbDisabled.IsChecked      = $true }
        1       { $script:_admxRbEnabled.IsChecked       = $true }
        default { $script:_admxRbNotConfigured.IsChecked = $true }
    }

    $script:_admxLblSettingName.Content    = "Setting: $($SettingObj.Name)"
    $script:_admxTxtSettings.Text          = [string]$SettingObj.PolicySettings
    $script:_admxChkManualConfig.IsChecked = [bool]$SettingObj.ManualConfig
    $script:_admxTxtSettingName.Text       = [string]$SettingObj.OMAURIName
    $script:_admxTxtSettingComment.Text    = [string]$SettingObj.Description

    if (-not $SettingObj.PolicyDefinition) {
        $SettingObj.PolicyDefinition = Format-XML $SettingObj.Definition.OuterXml
    }
    $script:_admxTxtPolicyDefinition.Text = [string]$SettingObj.PolicyDefinition

    if (-not $SettingObj.SupportedOn -and $SettingObj.Definition.supportedOn.ref) {
        $supRef = $SettingObj.Definition.supportedOn.ref.Split(':')[-1]
        $supObj = $script:_admxSupportedOn | Where-Object Id -eq $supRef
        if ($supObj) { $SettingObj.SupportedOn = $supObj.DisplayName }
    }
    $script:_admxTxtSupportedOn.Text = [string]$SettingObj.SupportedOn
    $script:_admxTxtDescription.Text = [string]$SettingObj.Description

    Set-ADMXElementsPanel $SettingObj
    Set-ADMXControlStatus
}

function Set-ADMXControlStatus
{
    # Element grid editable only when policy is Enabled AND not in manual mode.
    # Manual-mode TextBox is editable only when Enabled + manual mode.
    $manual = ($script:_admxChkManualConfig.IsChecked -eq $true)
    $script:_admxGrdElements.IsEnabled  = ($script:_admxCurItemStatus -eq 1 -and -not $manual)
    $script:_admxTxtSettings.IsReadOnly = (-not ($script:_admxCurItemStatus -eq 1 -and $manual))
}

function Save-ADMXSettings
{
    $item = $script:dgADMXCategoryPolicies.SelectedItem
    if (-not $item) { return }

    if ($script:_admxChkManualConfig.IsChecked -eq $true) {
        $item.PolicySettings = $script:_admxTxtSettings.Text
    } else {
        $item.PolicySettings = Get-ADMXSettingsString $item
    }
    $item.ManualConfig  = if ($script:_admxChkManualConfig.IsChecked -eq $true) { 1 } else { 0 }
    $item.SettingStatus = $script:_admxCurItemStatus
    $item.OMAURIName    = $script:_admxTxtSettingName.Text
    Set-ADMXSettingStatusText $item

    # Avalonia has no CollectionViewSource.Refresh; rebuild the ObservableCollection
    # to push the new SettingStatusText / PolicySettings into the grid cells.
    $current = @($script:dgADMXCategoryPolicies.ItemsSource)
    $script:dgADMXCategoryPolicies.ItemsSource = [System.Collections.ObjectModel.ObservableCollection[object]]::new($current)

    $script:_admxGrdElements.Children.Clear()
}

function Add-ADMXGridObject
{
    # Avalonia equivalent of WPF Add-GridObject — appends an Auto-height row to
    # the target Grid, sets Grid.Row on the control, and adds it.
    param($Grid, $Obj)

    $rd = [Avalonia.Controls.RowDefinition]::new()
    $rd.Height = [Avalonia.Controls.GridLength]::Auto
    [Avalonia.Controls.Grid]::SetRow($Obj, $Grid.RowDefinitions.Count)
    [void]$Grid.RowDefinitions.Add($rd)
    [void]$Grid.Children.Add($Obj)
}

function Add-ADMXListEditorButtons
{
    # Avalonia DataGrid lacks CanUserAddRows / CanUserDeleteRows — mount an
    # Add / Remove button bar under the DataGrid so listBox elements stay
    # usable. Buttons close over $DataGrid via .Tag.
    param($Grid, $DataGrid)

    $sp = [Avalonia.Controls.StackPanel]::new()
    $sp.Orientation         = [Avalonia.Layout.Orientation]::Horizontal
    $sp.HorizontalAlignment = [Avalonia.Layout.HorizontalAlignment]::Right
    $sp.Margin              = [Avalonia.Thickness]::new(0, 5, 0, 0)

    $btnAdd = [Avalonia.Controls.Button]::new()
    $btnAdd.Content  = 'Add row'
    $btnAdd.MinWidth = 80
    $btnAdd.Tag      = $DataGrid
    $btnAdd.add_Click((ConvertTo-AvaloniaEventScriptBlock {
        param($S, $E)
        $dg = $S.Tag
        try { [void]$dg.CommitEdit([Avalonia.Controls.DataGridEditingUnit]::Cell, $true) } catch { }
        try { [void]$dg.CommitEdit([Avalonia.Controls.DataGridEditingUnit]::Row,  $true) } catch { }

        $items = $dg.ItemsSource
        if (-not ($items -is [System.Collections.ObjectModel.ObservableCollection[ADMXListValueItem]])) {
            $items = New-ADMXListItemsCollection $items
            $dg.ItemsSource = $items
        }
        $items.Add([ADMXListValueItem]::new())
        $dg.SelectedIndex = $items.Count - 1
    }))

    $btnRemove = [Avalonia.Controls.Button]::new()
    $btnRemove.Content  = 'Remove'
    $btnRemove.MinWidth = 80
    $btnRemove.Margin   = [Avalonia.Thickness]::new(5, 0, 0, 0)
    $btnRemove.Tag      = $DataGrid
    $btnRemove.add_Click((ConvertTo-AvaloniaEventScriptBlock {
        param($S, $E)
        $dg = $S.Tag
        if ($dg.SelectedIndex -lt 0) { return }
        try { [void]$dg.CommitEdit([Avalonia.Controls.DataGridEditingUnit]::Cell, $true) } catch { }
        try { [void]$dg.CommitEdit([Avalonia.Controls.DataGridEditingUnit]::Row,  $true) } catch { }

        $items = $dg.ItemsSource
        if (-not ($items -is [System.Collections.ObjectModel.ObservableCollection[ADMXListValueItem]])) {
            $items = New-ADMXListItemsCollection $items
            $dg.ItemsSource = $items
        }
        $items.RemoveAt($dg.SelectedIndex)
    }))

    [void]$sp.Children.Add($btnAdd)
    [void]$sp.Children.Add($btnRemove)
    Add-ADMXGridObject $Grid $sp
}

function Set-ADMXComboDisplayMember
{
    # ADMX presentation combos are built in code, so they get their display
    # field here instead of in .axaml. Items are [SettingsListItem].
    param($ComboBox)

    if (-not $ComboBox) { return }
    $ComboBox.DisplayMemberBinding = [Avalonia.Data.Binding]::new('Name')

    # Avalonia's ComboBox defaults to HorizontalAlignment=Left (TextBox and
    # most other controls default to Stretch), so a combo dropped into the
    # elements grid collapses to ~64px in a 424px column instead of filling
    # it like the WPF original. Measured 2026-08-27.
    $ComboBox.HorizontalAlignment = [Avalonia.Layout.HorizontalAlignment]::Stretch
}

function New-ADMXListItemsCollection
{
    param($Items)

    $collection = [System.Collections.ObjectModel.ObservableCollection[ADMXListValueItem]]::new()
    foreach ($item in @($Items)) {
        if ($null -eq $item) { continue }
        if ($item -is [ADMXListValueItem]) {
            $collection.Add($item)
        }
        else {
            $row = [ADMXListValueItem]::new()
            if ($null -ne $item.Key)   { $row.Key   = [string]$item.Key }
            if ($null -ne $item.Value) { $row.Value = [string]$item.Value }
            $collection.Add($row)
        }
    }
    return ,$collection
}

function Set-ADMXListGridDefaults
{
    param($DataGrid)

    if (-not $DataGrid) { return }
    $DataGrid.CanUserSortColumns       = $false
    $DataGrid.CanUserResizeColumns     = $true
    $DataGrid.AutoGenerateColumns      = $false
    $DataGrid.IsReadOnly               = $false
    $DataGrid.HorizontalAlignment      = [Avalonia.Layout.HorizontalAlignment]::Stretch
    $DataGrid.ColumnWidth              = [Avalonia.Controls.DataGridLength]::new(1, [Avalonia.Controls.DataGridLengthUnitType]::Star)
    $DataGrid.MinHeight                = 72
    $DataGrid.MaxHeight                = 120
    $DataGrid.RowHeight                = 28
    $DataGrid.ColumnHeaderHeight       = 28
    $DataGrid.VerticalScrollBarVisibility   = [Avalonia.Controls.Primitives.ScrollBarVisibility]::Auto
    $DataGrid.HorizontalScrollBarVisibility = [Avalonia.Controls.Primitives.ScrollBarVisibility]::Disabled
}

function Set-ADMXElementsPanel
{
    # Build per-element editor controls for a policy. Layout matches the WPF
    # version 1:1; only the control types and grid attached props change.
    param($Item)

    if (-not $Item.Definition.elements) { return }

    if (-not $Item.ElementsPanel) {
        $grd = [Avalonia.Controls.Grid]::new()
        $grd.HorizontalAlignment = [Avalonia.Layout.HorizontalAlignment]::Stretch
        $presentation = Get-ADMXPresentationNode $Item

        if ($presentation) {
            foreach ($presentationNode in $presentation.ChildNodes) {
                $ctrl = $null
                $elementNode = $Item.Definition.elements.ChildNodes | Where-Object id -eq $presentationNode.refId

                if     ($presentationNode.Label.'#text') { $stringLabel = $presentationNode.Label.'#text' }
                elseif ($presentationNode.Label)         { $stringLabel = $presentationNode.Label }
                else                                     { $stringLabel = $presentationNode.'#text' }

                if ($stringLabel -and $presentationNode.LocalName -ne 'CheckBox') {
                    $ctrl = [Avalonia.Controls.TextBlock]::new()
                    $ctrl.Text = [string]$stringLabel
                    Add-ADMXGridObject $grd $ctrl
                }

                if ($presentationNode.LocalName -eq 'text') { continue }

                if ($ctrl) { $ctrl.Margin = [Avalonia.Thickness]::new(0, 5, 0, 0) }

                switch ($presentationNode.LocalName)
                {
                    'textbox' {
                        $ctrl = [Avalonia.Controls.TextBox]::new()
                        if ($null -ne $presentationNode.defaultValue) { $ctrl.Text = [string]$presentationNode.defaultValue }
                    }
                    { $_ -in @('DecimalTextBox','LongDecimalTextBox') } {
                        $ctrl = [Avalonia.Controls.NumericUpDown]::new()
                        $ctrl.Minimum   = [decimal](?? $elementNode.minValue 0)
                        $ctrl.Maximum   = [decimal](?? $elementNode.maxValue 9999)
                        $ctrl.Increment = [decimal](?? $elementNode.SpinStep 1)
                        $ctrl.FormatString = '0'
                        if ($null -ne $presentationNode.defaultValue) {
                            try { $ctrl.Value = [decimal]$presentationNode.defaultValue } catch { }
                        }
                    }
                    'multiText' {
                        $ctrl = [Avalonia.Controls.TextBox]::new()
                        $ctrl.Height        = 100
                        $ctrl.AcceptsReturn = $true
                    }
                    'CheckBox' {
                        $ctrl = [Avalonia.Controls.CheckBox]::new()
                        $ctrl.Content = [string]$stringLabel
                        if ($presentationNode.defaultChecked -eq $true) { $ctrl.IsChecked = $true }
                    }
                    { $_ -in @('ComboBox','DropdownList') } {
                        $ctrl = [Avalonia.Controls.ComboBox]::new()
                        Set-ADMXComboDisplayMember $ctrl

                        $valItems = @()
                        foreach ($valItem in $elementNode.ChildNodes) {
                            $displayName = Get-ADMXADMLString $valItem
                            $value = $null
                            if     ($valItem.value.decimal.value)   { $value = $valItem.value.decimal.value }
                            elseif ($valItem.value.longDecimal)     { $value = (?? $valItem.value.longDecimal.'#text' $valItem.value.longDecimal) }
                            elseif ($valItem.value.string)          { $value = (?? $valItem.value.string.'#text'      $valItem.value.string) }
                            else {
                                Write-Log "Unsupported value type for $($elementNode.Id): $($valItem.value.InnerXml)" 2
                                $value = '<SET MANUALLY!!!>'
                            }
                            $valItems += [SettingsListItem]@{ Name = [string]$displayName; Value = $value }
                        }
                        # Cast back to a typed array, don't just pipe. Sort-Object
                        # collapses a single item to a scalar (ItemsSource then
                        # throws) and re-wraps every item in a PSObject, which the
                        # binder cannot see through - DisplayMemberBinding would
                        # render blank rows. The [SettingsListItem[]] cast fixes both.
                        if ($presentationNode.NoSort -ne 'true') {
                            $valItems = [SettingsListItem[]]@($valItems | Sort-Object -Property Name)
                        }
                        $ctrl.ItemsSource = $valItems
                        if ($null -ne $presentationNode.defaultItem) {
                            try { $ctrl.SelectedIndex = [int]$presentationNode.defaultItem } catch { }
                        }
                    }
                    'listBox' {
                        $ctrl = [Avalonia.Controls.DataGrid]::new()
                        Set-ADMXListGridDefaults $ctrl

                        $col = [Avalonia.Controls.DataGridTextColumn]::new()
                        $col.Header  = 'Value Name'
                        $col.Width   = [Avalonia.Controls.DataGridLength]::new(1, [Avalonia.Controls.DataGridLengthUnitType]::Star)
                        $col.Binding = [Avalonia.Data.Binding]::new('Key')
                        $col.Binding.Mode = [Avalonia.Data.BindingMode]::TwoWay
                        $col.Binding.UpdateSourceTrigger = [Avalonia.Data.UpdateSourceTrigger]::PropertyChanged
                        if ($elementNode.explicitValue -ne 'true') { $col.IsVisible = $false }
                        [void]$ctrl.Columns.Add($col)

                        $col = [Avalonia.Controls.DataGridTextColumn]::new()
                        $col.Header  = 'Value'
                        $col.Width   = [Avalonia.Controls.DataGridLength]::new(1, [Avalonia.Controls.DataGridLengthUnitType]::Star)
                        $col.Binding = [Avalonia.Data.Binding]::new('Value')
                        $col.Binding.Mode = [Avalonia.Data.BindingMode]::TwoWay
                        $col.Binding.UpdateSourceTrigger = [Avalonia.Data.UpdateSourceTrigger]::PropertyChanged
                        [void]$ctrl.Columns.Add($col)

                        $ctrl.ItemsSource = New-ADMXListItemsCollection
                    }
                    default {
                        Write-Log "Unsupported presentation control: $($presentationNode.LocalName) (refId: $($presentationNode.refId))" 2
                        continue
                    }
                }

                if ($ctrl) {
                    Add-ADMXGridObject $grd $ctrl
                    if ($presentationNode.refId) {
                        $ctrl.Tag  = $elementNode
                        $ctrl.Name = $presentationNode.refId
                    }
                    if ($presentationNode.LocalName -eq 'listBox') {
                        Add-ADMXListEditorButtons $grd $ctrl
                    }
                }
            }
        }
        else {
            # Fallback: no presentation. Best-effort controls straight from <elements>.
            Write-Log "No presentation found for $($Item.Definition.Name); building fallback editor" 2
            foreach ($elementNode in $Item.Definition.elements.ChildNodes) {
                try {
                    $ctrl = $null
                    switch ($elementNode.LocalName) {
                        'text'      { $ctrl = [Avalonia.Controls.TextBox]::new() }
                        'multiText' {
                            $ctrl = [Avalonia.Controls.TextBox]::new()
                            $ctrl.Height        = 100
                            $ctrl.AcceptsReturn = $true
                        }
                        'enum' {
                            $ctrl = [Avalonia.Controls.ComboBox]::new()
                            Set-ADMXComboDisplayMember $ctrl

                            $valItems = @()
                            foreach ($valItem in $elementNode.ChildNodes) {
                                $value = $null
                                if     ($valItem.value.decimal.value) { $value = $valItem.value.decimal.value }
                                elseif ($valItem.value.string)        { $value = (?? $valItem.value.string.'#text' $valItem.value.string) }
                                else                                  { $value = '<SET MANUALLY!!!>' }
                                $valItems += [SettingsListItem]@{ Name = [string](Get-ADMXADMLString $valItem); Value = $value }
                            }
                            $ctrl.ItemsSource = $valItems
                        }
                        'list' {
                            $ctrl = [Avalonia.Controls.DataGrid]::new()
                            Set-ADMXListGridDefaults $ctrl
                            $col = [Avalonia.Controls.DataGridTextColumn]::new()
                            $col.Header  = 'Value Name'
                            $col.Width   = [Avalonia.Controls.DataGridLength]::new(1, [Avalonia.Controls.DataGridLengthUnitType]::Star)
                            $col.Binding = [Avalonia.Data.Binding]::new('Key')
                            $col.Binding.Mode = [Avalonia.Data.BindingMode]::TwoWay
                            $col.Binding.UpdateSourceTrigger = [Avalonia.Data.UpdateSourceTrigger]::PropertyChanged
                            if ($elementNode.explicitValue -ne 'true') { $col.IsVisible = $false }
                            [void]$ctrl.Columns.Add($col)
                            $col = [Avalonia.Controls.DataGridTextColumn]::new()
                            $col.Header  = 'Value'
                            $col.Width   = [Avalonia.Controls.DataGridLength]::new(1, [Avalonia.Controls.DataGridLengthUnitType]::Star)
                            $col.Binding = [Avalonia.Data.Binding]::new('Value')
                            $col.Binding.Mode = [Avalonia.Data.BindingMode]::TwoWay
                            $col.Binding.UpdateSourceTrigger = [Avalonia.Data.UpdateSourceTrigger]::PropertyChanged
                            [void]$ctrl.Columns.Add($col)
                            $ctrl.ItemsSource = New-ADMXListItemsCollection
                        }
                        'decimal' {
                            $ctrl = [Avalonia.Controls.NumericUpDown]::new()
                            $ctrl.FormatString = '0'
                        }
                        'boolean' {
                            $ctrl = [Avalonia.Controls.CheckBox]::new()
                        }
                        default {
                            Write-Log "Element type not supported in fallback: $($elementNode.LocalName)" 2
                            continue
                        }
                    }

                    if ($null -eq $ctrl) { continue }

                    $displayName = Get-ADMXADMLPresentationString $presentation $elementNode
                    if ($displayName) {
                        $tb = [Avalonia.Controls.TextBlock]::new()
                        if ($grd.RowDefinitions.Count -gt 0) {
                            $tb.Margin = [Avalonia.Thickness]::new(0, 5, 0, 0)
                        }
                        $tb.Text = [string]$displayName
                        Add-ADMXGridObject $grd $tb
                    }

                    $ctrl.Tag  = $elementNode
                    $ctrl.Name = $elementNode.Id
                    Add-ADMXGridObject $grd $ctrl

                    if ($elementNode.LocalName -eq 'list') {
                        Add-ADMXListEditorButtons $grd $ctrl
                    }
                }
                catch {
                    Write-LogError "Failed to add ADMX element $($elementNode.LocalName) with id $($elementNode.id)" $_.Exception
                }
            }
        }

        # Trailing row so the grid stretches; harmless if empty.
        [void]$grd.RowDefinitions.Add([Avalonia.Controls.RowDefinition]::new())
        $Item.ElementsPanel = $grd
    }

    if ($Item.ElementsPanel) {
        # Detach from previous parent — Avalonia controls can only have one
        # logical parent, and re-opening the dialog re-mounts the same panel.
        if ($Item.ElementsPanel.Parent) {
            $oldParent = $Item.ElementsPanel.Parent
            if ($oldParent.Children -and $oldParent.Children.Contains($Item.ElementsPanel)) {
                [void]$oldParent.Children.Remove($Item.ElementsPanel)
            }
        }
        [void]$script:_admxGrdElements.Children.Add($Item.ElementsPanel)
    }
}

function Get-ADMXSettingsString
{
    # Build the OMA-URI <data id=... value=.../> XML from live element controls.
    # Empty values are skipped (with a log line for required ones). Returns the
    # joined string or $null if the policy isn't Enabled.
    param($Item)

    if (-not $Item -or -not $Item.Definition.elements) { return }
    if ($script:_admxCurItemStatus -ne 1) {
        $Item.PolicySettings = $null
        return
    }
    if (-not $Item.ElementsPanel) { return }

    $policySettings = @()
    foreach ($elementNode in $Item.Definition.elements.ChildNodes) {
        $ctrl = $Item.ElementsPanel.Children | Where-Object { $_.Name -eq $elementNode.Id } | Select-Object -First 1
        if (-not $ctrl) {
            Write-Log "Could not find a control with id $($elementNode.Id)" 3
            continue
        }

        $ctrlValue = $null
        switch ($elementNode.LocalName) {
            'text'      { $ctrlValue = $ctrl.Text }
            'multiText' { $ctrlValue = ($ctrl.Text -replace [Environment]::NewLine, '&#xF000;') }
            'enum' {
                if ($ctrl.SelectedItem) { $ctrlValue = $ctrl.SelectedItem.Value }
            }
            'list' {
                try { [void]$ctrl.CommitEdit([Avalonia.Controls.DataGridEditingUnit]::Cell, $true) } catch { }
                try { [void]$ctrl.CommitEdit([Avalonia.Controls.DataGridEditingUnit]::Row,  $true) } catch { }

                $i = 1
                $arr = @()
                foreach ($kv in $ctrl.ItemsSource) {
                    if (-not $kv.Value) { continue }
                    $arr += "$((?? $kv.Key $i))&#xF000;$($kv.Value)"
                    $i++
                }
                $ctrlValue = $arr -join '&#xF000;'
            }
            default {
                if ($elementNode.LocalName -eq 'decimal' -or $ctrl.Tag.LocalName -eq 'longDecimal') {
                    if ($ctrl -is [Avalonia.Controls.NumericUpDown]) {
                        if ($null -ne $ctrl.Value) { $ctrlValue = $ctrl.Value.ToString() }
                    } else {
                        $ctrlValue = $ctrl.Text
                    }
                }
                elseif ($elementNode.LocalName -eq 'boolean') {
                    if ($ctrl -is [Avalonia.Controls.CheckBox]) {
                        $ctrlValue = if ($ctrl.IsChecked -eq $true) { '1' } else { '0' }
                    }
                    elseif ($ctrl -is [Avalonia.Controls.ComboBox]) {
                        if ($ctrl.SelectedItem) { $ctrlValue = $ctrl.SelectedItem.Value }
                    }
                    else {
                        Write-Log "Boolean element type not supported: $($elementNode.LocalName)" 2
                        continue
                    }
                }
                else {
                    Write-Log "Element type not supported: $($elementNode.LocalName)" 2
                    continue
                }
            }
        }

        if (-not $ctrlValue) {
            if ($elementNode.required -eq $true) {
                Write-Log "Required value is missing for $($elementNode.Id)" 3
            } else {
                Write-Log "Value not set for $($elementNode.Id) - value will not be added"
            }
            continue
        }

        $policySettings += "<data id=`"$($elementNode.Id)`" value=`"$ctrlValue`"/>"
    }
    return ($policySettings -join [Environment]::NewLine)
}

# ─── ADMX Import — Intune ingestion (Slice 5a4) ───────────────────────────────
#
# Direct port of UI/WPF/Extensions/IntuneToolsUI.ps1's Import-ADMXPolicyToIntune.
# No UI sub-dialog (the WPF tree's IntuneToolsADMXDriveMapping.xaml is dead
# code — never referenced from any handler), so the Avalonia version is a
# pure data-flow port: validate inputs → walk configured policies → POST a
# windows10CustomConfiguration to deviceManagement/deviceConfigurations.
function Import-ADMXPolicyToIntune
{
    $ui = $script:UIProvider
    if (-not $script:txtADMXProfileName.Text.Trim()) {
        $ui.ShowMessageBox('Profile Name must be specified', 'ADMX Import', 'OK', 'Error')
        return
    }
    if (-not $script:txtADMXPolicyFileName.Text.Trim()) {
        $ui.ShowMessageBox('ADMX Policy Name must be specified', 'ADMX Import', 'OK', 'Error')
        return
    }

    $configured = @()
    foreach ($admxPolicy in @($script:_admxPolicies | Where-Object { $_.SettingStatus -in @(0,1) })) {
        if ($admxPolicy.SettingStatus -eq 0) {
            $policyValue = '<disabled/>'
        }
        else {
            $policyValue = '<enabled/>'
            if ($admxPolicy.PolicySettings) { $policyValue += "`n$($admxPolicy.PolicySettings)" }
        }

        if ((Get-SettingValue 'FormatOMAURI') -eq $true) {
            $policyValue = Update-XmlFormatting $policyValue
        }

        $catPath = Get-ADMXCategoryOMAURIPath $admxPolicy.Definition.parentCategory.ref
        $omaUri  = "./$($admxPolicy.SettingClass)/Vendor/MSFT/Policy/Config/$($script:txtADMXPolicyAppName.Text)~Policy~$catPath/$($admxPolicy.Definition.name)"

        $desc =
            if ($admxPolicy.OMAURIDescription) { $admxPolicy.OMAURIDescription }
            elseif ($admxPolicy.Description -and $admxPolicy.Description.Length -gt 1000) { $admxPolicy.Description.Substring(0, 1000) }
            else { $admxPolicy.Description }

        $configured += [PSCustomObject]@{
            '@odata.type' = '#microsoft.graph.omaSettingString'
            displayName   = (?? $admxPolicy.OMAURIName $admxPolicy.Name)
            description   = $desc
            omaUri        = $omaUri
            value         = $policyValue
        }
    }

    $intuneObj = [PSCustomObject]@{
        '@odata.type'   = '#microsoft.graph.windows10CustomConfiguration'
        displayName     = $script:txtADMXProfileName.Text
        omaSettings     = @()
        roleScopeTagIds = @()
        assignments     = @()
    }
    if ($script:txtADMXProfileDescription.Text) {
        $intuneObj | Add-Member -MemberType NoteProperty -Name 'description' -Value $script:txtADMXProfileDescription.Text
    }

    if ($script:chkADMXPolicyIngest.IsChecked) {
        $xmlString = Format-XML $script:_admxXML
        if ((Get-SettingValue 'FormatOMAURI') -eq $true) {
            $xmlString = Update-XmlFormatting $xmlString
        }

        $ingestName = if ($script:txtADMXPolicyIngestName.Text) { $script:txtADMXPolicyIngestName.Text }
                      else { "$($script:currentADMXFile.Name) Ingestion" }

        $intuneObj.omaSettings += [PSCustomObject]@{
            '@odata.type' = '#microsoft.graph.omaSettingString'
            displayName   = $ingestName
            description   = $null
            omaUri        = "./Device/Vendor/MSFT/Policy/ConfigOperations/ADMXInstall/$($script:txtADMXPolicyAppName.Text)/Policy/$($script:txtADMXPolicyFileName.Text)"
            value         = $xmlString
        }
    }

    $intuneObj.omaSettings += $configured
    $json = $intuneObj | ConvertTo-Json -Depth 20

    $tokenId = Get-DefaultTokenId
    $resp = Invoke-MSGraphAPI -Url 'deviceManagement/deviceConfigurations' -Content $json -HttpMethod 'POST' -TokenId $tokenId -FullResponseObject

    if ($resp -and $resp.Success) {
        Write-Log "Device configuration profile '$($intuneObj.displayName)' created with id $($resp.Content.Id)"
        $ui.ShowMessageBox("Profile '$($intuneObj.displayName)' created successfully.", 'ADMX Import', 'OK', 'Information')
    }
    else {
        $errInfo = if ($resp) { "$($resp.StatusCode) $($resp.StatusDescription)" } else { 'no response' }
        Write-Log "Failed to create device configuration profile '$($intuneObj.displayName)' - $errInfo" 3
        $ui.ShowMessageBox("Failed to create device configuration profile '$($intuneObj.displayName)'.`n`n$errInfo`n`nCheck the log for details.", 'ADMX Import', 'OK', 'Error')
    }
}

