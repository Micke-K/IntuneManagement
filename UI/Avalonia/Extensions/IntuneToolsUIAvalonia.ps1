# port of the IntuneTools view so its left-nav items render and clicking them
# swaps placeholder content into grdToolsMain. The four real tool bodies
# (Show-IntuneAssignmentsTool, Show-IntuneFilterUsageTool, Show-ADMXImportTool,
# Show-ADMXRegValuesTool — ~2500 lines in the WPF file) are NOT ported yet;
# each is currently a placeholder TextBlock saying "not yet ported".

